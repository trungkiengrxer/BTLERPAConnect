static void patchedCsValidatePage(
    vnode_t vnode,
    memory_object_t pager,
    memory_object_offset_t pageOffset,
    const void *data,
    int *validated,
    int *tainted,
    int *nx
) {
    FunctionCast(
        patchedCsValidatePage,
        originalCsValidatePage
    )(vnode, pager, pageOffset, data, validated, tainted, nx);

    if (data == nullptr)
        return;

    char path[PATH_MAX] {};
    int pathLength = sizeof(path);

    if (vn_getpath(vnode, path, &pathLength) != 0)
        return;

    if (strcmp(path, bluetoothdPath) != 0)
        return;

    // Patch on every page-in: the page cache can drop and reload the page.
    // The routines and the call sites sit on different pages, so a call site
    // can be patched before its routine page is read; that page is patched
    // when it faults in, before any code on it runs.
    auto page = static_cast<uint8_t *>(const_cast<void *>(data));

    for (size_t i = 0; i < arrsize(patches); i++) {
        const auto &patch = patches[i];
        size_t at = 0;

        if (!KernelPatcher::findPattern(patch.anchor, nullptr, patch.anchorSize, page, PAGE_SIZE, &at))
            continue;

        at += patch.offset;

        if (at + patch.size > PAGE_SIZE || memcmp(page + at, patch.original, patch.size) != 0)
            continue;

        memcpy(page + at, patch.replacement, patch.size);

        {
            SYSLOG(
                MODULE_SHORT,
                "applied %s in %s at page offset 0x%llx",
                patch.name,
                path,
                static_cast<unsigned long long>(pageOffset)
            );
        }
    }
}

static void pluginStart() {
    DBGLOG(MODULE_SHORT, "BTLERPAConnect starting");

    lilu.onPatcherLoadForce([](void *, KernelPatcher &patcher) {
        KernelPatcher::RouteRequest request(
            "_cs_validate_page",
            patchedCsValidatePage,
            originalCsValidatePage
        );

        if (!patcher.routeMultipleLong(KernelPatcher::KernelID, &request, 1))
            SYSLOG(MODULE_SHORT, "failed to route _cs_validate_page");
    });
}

