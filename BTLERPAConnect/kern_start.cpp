// Replace `original` with `replacement` at `offset` bytes after `anchor`.
// For in-place patches the anchor is the original bytes themselves.
struct BluetoothdPatch {
    const uint8_t *anchor;
    size_t anchorSize;
    size_t offset;
    const uint8_t *original;
    const uint8_t *replacement;
    size_t size;
    const char *name;
};

