//
//  kern_start.cpp
//  BTLERPAConnect.kext
//
//  Runtime patches for /usr/sbin/bluetoothd (macOS Tahoe 26.6, 25G72, x86_64)
//  on non-Apple Broadcom BCM20702 controllers (e.g. DW1560), so LE links
//  used by Instant Hotspot are not torn down. Independent of BTLEAdvFix.
//
//  1. No false "FW is in UHE Mode" restart
//     The first HCI command rejected with "Command Disallowed" (0x0C) makes
//     bluetoothd send Apple's BD_VSC_READ_FW_INFO (fcfe 04). The BCM20702
//     rejects it (STATUS 701), readCurrentUHEModeCB stores mode 0, the check
//     treats any mode != 2 as a firmware crash and bluetoothd restarts itself
//     (reason 654), dropping every LE link. BCM20702 is a BT 4.0 controller,
//     so it answers 0x0C whenever connectable advertising overlaps initiating
//     or a connection: every LE connection attempt, in or out, hits this.
//     Store 2 (normal) when the command fails.
//
//       0x10033cbfd  xorl %eax,%eax  -> movb $0x2,%al
//       0x10033cbff  movb %al, 0x100b3a7a0
//
//  2. Scannable advertising only while connecting or connected
//     BT 4.0 has no "connectable advertising + initiating/connection" states,
//     so LE_CreateConn is rejected (0x0C) while the Mac advertises ADV_IND,
//     and advertising cannot restart while a link is up. When bluetoothd asks
//     for ADV_IND (0) and an LE_CreateConn is pending (lConnectionInProgress)
//     or an LE link is up, send ADV_SCAN_IND (2) instead; otherwise keep it.
//     ADV_SCAN_IND needs an interval of at least 0xA0 in BT 4.0, so faster
//     intervals are raised to 0xA0 in that case (the controller answers 0x12
//     otherwise and bluetoothd retries in a tight loop).
//     Switches go through bluetoothd's own silent restart (0x1001f6d42),
//     which disables advertising, resends the parameters and enables again:
//     - before LE_CreateConn, if the controller advertises connectable
//       (the disable is queued ahead of LE_CreateConn)
//     - when the last LE link goes and nothing is connecting
//
//       0x1001f5c66, 0x1001f6693  movzbl 0x100b294f4(%rip),%r8d -> call advType
//       0x10020537f  LE connect, before LE_CreateConn        -> call connectStart
//       0x100205ea4  second LE connect path, same place      -> call connectStart2
//       0x100214c06  GAP_ConnectionCompleteCallback status    -> call connComplete
//       0x100209514  LE disconnection complete                -> call disconnect
//
//  3. Connect to the iPhone's current RPA
//     Without LL privacy the controller only matches the address in the
//     accept list, but bluetoothd adds the identity address while the iPhone
//     advertises with a resolvable private address. Record identity -> RPA
//     whenever bluetoothd resolves an advertisement, and put that RPA in the
//     accept list (and remove the same RPA later).
//
//       0x100227190  identity stores in LE_ResolveAddress -> call resolveRecord
//       0x1002350ec  accept list add (cmd 0xb1) args     -> call acceptAdd
//       0x10023540c  accept list remove (cmd 0xb2) args  -> call acceptRemove
//       0x100aa2440  routines (docs/cave.s), after __eh_frame and after
//                    BTLEAdvFix's routine (ends 0x100aa2424)
//       0x100b52e40  16 x 24 byte table in the unused tail of __DATA,
//                    then the LE link count and the last advertising type
//

